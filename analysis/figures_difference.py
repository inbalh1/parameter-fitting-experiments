import pandas as pd
import numpy as np
import os
import seaborn as sns
import matplotlib.pyplot as plt
from matplotlib.figure import Figure
from scipy.stats import pearsonr
import argparse
import sys

sys.path.insert(0, 'src')
from models import ALL_MODELS

param_name_to_title = {
    'n': 'vertex count',
    'd': 'average degree',
    'beta': 'beta',
    't': 'temperature',
    'heterogeneity': 'heterogeneity',
    'cc': 'clustering coefficient'
}

# TODO: perhaps should also give output dir
class Analyzer:
    def __init__(self, fitter, model):
        # If fitter is None - its RobinsMonro (since we dont use a special folder for it)
        self.fitter = fitter
        self.model = model
        
        # Initialize input paths
        self.target_params_path = f"output_data/target_params/{self.model}.csv"
        if self.fitter:
            self.features_path = os.path.join("output_data", "fitted_features", self.fitter, f"{self.model}.csv")
            self.fitted_params_path = os.path.join("output_data", "fitted_params", self.fitter, f"{self.model}.csv")
        else:
            # Assume the fitter is our fitter (which has no destination folder)
            self.features_path = os.path.join("output_data", "fitted_features",f"{self.model}.csv")
            self.fitted_params_path = os.path.join("output_data", "fitted_params", f"{self.model}.csv")
        self.attributes_path = f"output_data/attributes/{self.model}.csv"
        
        # Initialize output paths
        if self.fitter:
            self.output_dir = os.path.join("output_data", "figures", self.fitter)
        else:
            self.output_dir = os.path.join("output_data", "figures")
    
    def execute(self):
        tbl = self.create_table()
        print(tbl.describe())
        
        results = []
        model_choices = {model.name().lower(): model for model in ALL_MODELS}
        model_class = model_choices[self.model]
        for param in model_class.input_parameters():
            feature_name = param.output_parameter().name()
            feature_title = param_name_to_title[feature_name]
            results.append(self.analyze_feature(tbl, feature_name))
            fig = self.plot_feature(tbl, feature=feature_name, feature_title=feature_title)
            self.save_figure(fig, feature=feature_name)
            param_title = param_name_to_title[param.name()]
            fig_param = self.plot_param(tbl, param=param.name(), param_title=param_title)
            # TODO: change name of parameter from feature to param
            self.save_figure(fig_param, feature=f'{param.name()}_param')

        # Mean iterations
        #print("Mean iterations:", tbl["total_iterations"].mean())

        # Write to file
        csv_path = os.path.join(self.output_dir, "analysis_result.csv")
        pd.DataFrame(results).to_csv(csv_path, index=False)
        

    def create_table(self):
        """
        Load data from several files and create a merge table with the following columns:
        # graph - graph name (e.g: erdos-renyi_n=1000_d=2_seed=142)
        # d, n - original parameters\ attributes (we sample graph from). e.g: 2, 1000
        # cc_true, 'd_true', 'heterogeneity_true', 'm_true', 'n_true' - this is not the ground-truth. This is the target features (expected values from original parameters)
        # 'cc_fitted', 'd_fitted', 'heterogeneity_fitted', 'm_fitted', 'n_fitted'
        # More info:, 'seed', 'Fitter',
        # 'd_fitting', 'n_fitting' - the parameters found by the fitter (parameters from which we sample graphs and measure the _fitted features)
        # 'target_d', 'target_n' - This is *also* the target features (it comes from the fitting table)
        """
        # Load data
        tbl_true = pd.read_csv(self.target_params_path)
        tbl_fitted = pd.read_csv(self.features_path)
        tbl_fitting_process = pd.read_csv(self.fitted_params_path)
        # Optional: modify 'graph' column to remove seed if needed
        # tbl_fitted["graph"] = tbl_fitted["graph"].str.replace(r"_seed=\d+$", "", regex=True)

        # Average numeric columns by graph
        tbl_fitted = tbl_fitted.groupby("graph").mean(numeric_only=True).reset_index()

        # Merge data
        tbl = pd.merge(tbl_true, tbl_fitted, on="graph", suffixes=("_true", "_fitted"))
        tbl_generation_params = pd.read_csv(self.attributes_path)
        tbl = pd.merge(tbl_generation_params, tbl, on="graph")
        tbl = pd.merge(tbl, tbl_fitting_process, on="graph", suffixes=("", "_fitting"))
        return tbl

    def analyze_feature(self, tbl: pd.DataFrame, feature:str):
        # Compares measured feature between graphs generated with ground-truth parameters, and graphs generated by fitter's parameters
        diff = abs(tbl[f"{feature}_true"] - tbl[f"{feature}_fitted"])
        sqdiff = diff**2
        corr, _ = pearsonr(tbl[f"{feature}_true"], tbl[f"{feature}_fitted"])
        result = {
            "feature": feature,
            "pearson_corr": corr,
            "mae": diff.mean(),
            "mse": sqdiff.mean()
        }
        print(f"{feature} Pearson correlation:", result['pearson_corr'])
        print(f"{feature} mean absolute difference:", result['mae'])
        print(f"{feature} mean squared error (MSE):", result['mse'])
        
        return result
        
    def plot_feature(self, tbl: pd.DataFrame, feature:str, feature_title:str) -> Figure:
        fig, ax = plt.subplots()
        true_feature = f"{feature}_true"
        fitted_feature = f"{feature}_fitted"
        try:
            sns.scatterplot(data=tbl, x=true_feature, y=fitted_feature, hue="total_iterations", palette="coolwarm", ax=ax, s=20, linewidth=0)
            ax.legend(title="Iterations", loc='center left', bbox_to_anchor=(1, 0.5))
        except Exception:
            sns.scatterplot(data=tbl, x=true_feature, y=fitted_feature, palette="coolwarm", ax=ax, s=20, linewidth=0)
        # Draw diagonal line
        ax.plot([tbl[true_feature].min(), tbl[true_feature].max()], [tbl[true_feature].min(), tbl[true_feature].max()], color="black", linewidth=0.5)
        ax.set_xlabel(f"Target {feature_title}")
        ax.set_ylabel(f"Mean actual {feature_title}")
        
        return fig

    def save_figure(self, fig: Figure, feature:str, width=0.45, height=0.5) -> None:
        os.makedirs(self.output_dir, exist_ok=True)
        path = os.path.join(self.output_dir, f"figure_{self.model}_difference_{feature}.pdf")
        fig.set_size_inches(width * 8.27, height * 11.69)  # Convert to A4 scale
        fig.savefig(path, bbox_inches='tight')
        plt.close(fig)


    def plot_param(self, tbl: pd.DataFrame, param:str, param_title:str) -> Figure:
        fig, ax = plt.subplots()
        true_val = f"{param}"
        measured_val = f"{param}_fitting"
        try:
            sns.scatterplot(data=tbl, x=true_val, y=measured_val, hue="total_iterations", palette="coolwarm", ax=ax, s=20, linewidth=0)
            ax.legend(title="Iterations", loc='center left', bbox_to_anchor=(1, 0.5))
        except Exception:
            sns.scatterplot(data=tbl, x=true_val, y=measured_val, palette="coolwarm", ax=ax, s=20, linewidth=0)
        ax.plot([tbl[true_val].min(), tbl[true_val].max()], [tbl[true_val].min(), tbl[true_val].max()], color="black", linewidth=0.5)
        ax.set_xlabel(f"Target {param_title}")
        ax.set_ylabel(f"Mean actual {param_title}")
        
        return fig

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument('--fitter', type=str, default=None)
    parser.add_argument('--model', type=str, default='erdos-renyi')

    args = parser.parse_args()

    fitter = args.fitter
